//! Term -> Triton source.
//!
//! The emitted program is deliberately the same two-stage shape that the
//! hand-written kernel uses and that P22 gated against `awq_gemm`: stage 1
//! computes one partial per k-slice with a plain store, stage 2 reduces the
//! partials. No atomics (P13 retracted the atomic version), which also
//! means the term's `reduce` op has an exact transcription rather than an
//! approximate one.

use crate::term::Qgemv;

/// Emit a Python module exposing `run(x, qw, qz, sc, n, k, bn, bk, warps)`.
pub fn emit(q: &Qgemv, block_n: usize, block_k: usize) -> String {
    let Qgemv { k, split, group } = *q;
    let header = format!(
        r#""""Generated by compile-triton from a kernel IR term (ADR-0165).

Do not edit: the geometry below came from the term, and `run` refuses a
shape the term was not lowered for.
"""

import torch
import triton
import triton.language as tl

K = {k}
SPLIT = {split}
GROUP = {group}
BLOCK_N_DEFAULT = {block_n}
BLOCK_K_DEFAULT = {block_k}
"#
    );

    let stage1 = r#"

@triton.jit
def _stage1(
    x_ptr,
    qw_ptr,
    qz_ptr,
    sc_ptr,
    part_ptr,
    N,
    K,
    GS,
    SPLIT,
    s_qwk,
    s_qwn,
    s_qzk,
    s_qzn,
    s_sck,
    s_scn,
    s_pk,
    s_pn,
    BLOCK_N: tl.constexpr,
    BLOCK_K: tl.constexpr,
):
    """One program per (output block, k slice); stores its partial."""
    pid_n = tl.program_id(0)
    pid_k = tl.program_id(1)
    rn = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)
    rw = pid_n * (BLOCK_N // 8) + tl.arange(0, BLOCK_N // 8)
    nmask = rn < N

    per = tl.cdiv(K, SPLIT * BLOCK_K) * BLOCK_K
    k_lo = pid_k * per
    k_hi = tl.minimum(k_lo + per, K)

    shift = tl.arange(0, 8) * 4
    acc = tl.zeros((BLOCK_N,), dtype=tl.float32)

    for k0 in range(k_lo, k_hi, BLOCK_K):
        rk = k0 + tl.arange(0, BLOCK_K)
        kmask = rk < K
        g = rk // GS
        wmask = kmask[:, None] & (rw < (N + 7) // 8)[None, :]
        words = tl.load(
            qw_ptr + rk[:, None] * s_qwk + rw[None, :] * s_qwn,
            mask=wmask,
            other=0,
            eviction_policy="evict_first",
        )
        q = ((words[:, :, None] >> shift[None, None, :]) & 0xF).reshape(
            BLOCK_K, BLOCK_N
        )
        zwords = tl.load(
            qz_ptr + g[:, None] * s_qzk + rw[None, :] * s_qzn,
            mask=wmask,
            other=0,
            eviction_policy="evict_first",
        )
        z = ((zwords[:, :, None] >> shift[None, None, :]) & 0xF).reshape(
            BLOCK_K, BLOCK_N
        )
        s = tl.load(
            sc_ptr + g[:, None] * s_sck + rn[None, :] * s_scn,
            mask=kmask[:, None] & nmask[None, :],
            other=0.0,
        ).to(tl.float32)
        w = (q.to(tl.float32) - z.to(tl.float32)) * s
        x = tl.load(x_ptr + rk, mask=kmask, other=0.0).to(tl.float32)
        acc += tl.sum(w * x[:, None], axis=0)

    tl.store(part_ptr + pid_k * s_pk + rn * s_pn, acc, mask=nmask)
"#;

    let reduce = r#"

@triton.jit
def _reduce(part_ptr, out_ptr, N, SPLIT, s_pk, s_pn, BLOCK: tl.constexpr):
    """Sum the SPLIT partial rows into the fp16 output."""
    pid = tl.program_id(0)
    rn = pid * BLOCK + tl.arange(0, BLOCK)
    mask = rn < N
    acc = tl.zeros((BLOCK,), dtype=tl.float32)
    for j in range(SPLIT):
        acc += tl.load(
            part_ptr + j * s_pk + rn * s_pn, mask=mask, other=0.0
        )
    tl.store(out_ptr + rn, acc.to(tl.float16), mask=mask)
"#;

    let runner = r#"

def run(x, qw, qz, sc, n, k, bn=BLOCK_N_DEFAULT, bk=BLOCK_K_DEFAULT,
        warps=2, out=None):
    """Run the lowered kernel. The term, not the caller, fixes K/SPLIT."""
    if k != K:
        raise ValueError(f"lowered for K={K}, called with k={k}")
    parts = torch.empty((SPLIT, n), device="cuda", dtype=torch.float32)
    _stage1[(triton.cdiv(n, bn), SPLIT)](
        x,
        qw,
        qz,
        sc,
        parts,
        n,
        k,
        GROUP,
        SPLIT,
        qw.stride(0),
        qw.stride(1),
        qz.stride(0),
        qz.stride(1),
        sc.stride(0),
        sc.stride(1),
        parts.stride(0),
        parts.stride(1),
        BLOCK_N=bn,
        BLOCK_K=bk,
        num_warps=warps,
    )
    if out is None:
        out = torch.empty((1, n), device="cuda", dtype=torch.float16)
    _reduce[(triton.cdiv(n, 128),)](
        parts,
        out,
        n,
        SPLIT,
        parts.stride(0),
        parts.stride(1),
        BLOCK=128,
    )
    return out
"#;

    format!("{header}{stage1}{reduce}{runner}")
}
