//! Term -> Triton source.
//!
//! The emitted program is deliberately the same two-stage shape that the
//! hand-written kernel uses and that P22 gated against `awq_gemm`: stage 1
//! computes one partial per k-slice with a plain store, stage 2 reduces the
//! partials. No atomics (P13 retracted the atomic version), which also
//! means the term's `reduce` op has an exact transcription rather than an
//! approximate one.
//!
//! The stage-1 body is the P25 revision: `sum_k (q - z_g) s_g x` is
//! algebraically `s_g * (sum q*x) - s_g * z_g * (sum x)`, so the zero-point
//! and scale work drops from O(BLOCK_K*BLOCK_N) per block to O(BLOCK_N) —
//! that hoisting alone moved the emitted kernel from 46 % to 66 % of the
//! memory roofline on the RTX 2050. The nibble->fp16 conversion uses the
//! magic-number form `(w >> s & 0xF) | 0x6400`, reinterpreted (`1024 + q`)
//! minus 1024 — a LOP3 + fp16 subtract instead of an int->float convert —
//! and `qw` is read as int64 when the operand's last dim is even (halved
//! load instructions). Measured: ~80-86 % of roofline, cosine 1.000000
//! against the torch dequant reference (`graphopt` p25_roofline_arm).

use crate::term::{Elementwise, Expr, Lit, Operand, Qgemv, View};

/// Emit a Python module exposing `run(x, qw, qz, sc, n, k, bn, bk, warps)`.
pub fn emit(q: &Qgemv, block_n: usize, block_k: usize) -> String {
    let Qgemv {
        k,
        split,
        group,
        depth,
    } = *q;
    let header = format!(
        r#""""Generated by compile-triton from a kernel IR term (ADR-0165).

Do not edit: the geometry below came from the term, and `run` refuses a
shape the term was not lowered for. Stage-1 body is the P25 revision —
group-hoisted dequant with fp16 magic-number unpack (see the module
docstring in src/codegen.rs).
"""

import torch
import triton
import triton.language as tl

K = {k}
SPLIT = {split}
GROUP = {group}
PIPELINE_DEPTH = {depth}
BLOCK_N_DEFAULT = {block_n}
BLOCK_K_DEFAULT = {block_k}
"#
    );

    let stage1 = r#"

@triton.jit
def _stage1(
    x_ptr,
    qw_ptr,
    qz_ptr,
    sc_ptr,
    part_ptr,
    N,
    K,
    GS,
    SPLIT,
    s_qwk,
    s_qwn,
    s_qzk,
    s_qzn,
    s_sck,
    s_scn,
    s_pk,
    s_pn,
    BLOCK_N: tl.constexpr,
    BLOCK_K: tl.constexpr,
):
    """One program per (output block, k slice); stores its partial.

    `sum (q-z)s x = s*(sum q*x) - s*z*(sum x)` per k-block, so z and s are
    handled once per block instead of once per element. Each block lies
    inside one quant group because BLOCK_K and GS are powers of two and
    k0 is a multiple of BLOCK_K (`run` rejects BLOCK_K > GS).
    """
    pid_n = tl.program_id(0)
    pid_k = tl.program_id(1)
    rn = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)
    rw = pid_n * (BLOCK_N // 8) + tl.arange(0, BLOCK_N // 8)
    nmask = rn < N
    wmask_row = rw < (N + 7) // 8

    per = tl.cdiv(K, SPLIT * BLOCK_K) * BLOCK_K
    k_lo = pid_k * per
    k_hi = tl.minimum(k_lo + per, K)

    shift = tl.arange(0, 8) * 4
    acc = tl.zeros((BLOCK_N,), dtype=tl.float32)

    for k0 in range(k_lo, k_hi, BLOCK_K):
        rk = k0 + tl.arange(0, BLOCK_K)
        kmask = rk < K
        words = tl.load(
            qw_ptr + rk[:, None] * s_qwk + rw[None, :] * s_qwn,
            mask=kmask[:, None] & wmask_row[None, :],
            other=0,
            eviction_policy="evict_first",
        )
        m = (
            ((words[:, :, None] >> shift[None, None, :]) & 0xF) | 0x6400
        ).reshape(BLOCK_K, BLOCK_N)
        q = m.to(tl.uint16).to(tl.float16, bitcast=True) - 1024.0
        x = tl.load(x_ptr + rk, mask=kmask, other=0.0)
        prod = (q * x[:, None]).to(tl.float32)
        pqx = tl.sum(prod, axis=0)
        xs = tl.sum(x.to(tl.float32), axis=0)

        g = k0 // GS  # scalar: the whole block is one quant group
        zwords = tl.load(
            qz_ptr + g * s_qzk + rw * s_qzn, mask=wmask_row, other=0
        )
        zm = ((zwords[:, None] >> shift[None, :]) & 0xF) | 0x6400
        z = (
            zm.reshape(BLOCK_N).to(tl.uint16).to(tl.float16, bitcast=True)
            - 1024.0
        ).to(tl.float32)
        s = tl.load(
            sc_ptr + g * s_sck + rn * s_scn, mask=nmask, other=0.0
        ).to(tl.float32)
        acc += s * (pqx - z * xs)

    tl.store(part_ptr + pid_k * s_pk + rn * s_pn, acc, mask=nmask)


@triton.jit
def _stage1_w64(
    x_ptr,
    qw_ptr,
    qz_ptr,
    sc_ptr,
    part_ptr,
    N,
    K,
    GS,
    SPLIT,
    s_qwk,
    s_qwn,
    s_qzk,
    s_qzn,
    s_sck,
    s_scn,
    s_pk,
    s_pn,
    BLOCK_N: tl.constexpr,
    BLOCK_K: tl.constexpr,
):
    """`_stage1` with `qw` read as int64 [K, N/16] — half the loads.

    `run` picks this only when `qw` is contiguous with an even word
    count per row, which implies N % 16 == 0.
    """
    pid_n = tl.program_id(0)
    pid_k = tl.program_id(1)
    rn = pid_n * BLOCK_N + tl.arange(0, BLOCK_N)
    rw = pid_n * (BLOCK_N // 16) + tl.arange(0, BLOCK_N // 16)
    nmask = rn < N
    wmask_row = rw < (N + 15) // 16

    per = tl.cdiv(K, SPLIT * BLOCK_K) * BLOCK_K
    k_lo = pid_k * per
    k_hi = tl.minimum(k_lo + per, K)

    shift = tl.arange(0, 8) * 4
    acc = tl.zeros((BLOCK_N,), dtype=tl.float32)

    for k0 in range(k_lo, k_hi, BLOCK_K):
        rk = k0 + tl.arange(0, BLOCK_K)
        kmask = rk < K
        w64 = tl.load(
            qw_ptr + rk[:, None] * s_qwk + rw[None, :] * s_qwn,
            mask=kmask[:, None] & wmask_row[None, :],
            other=0,
            eviction_policy="evict_first",
        )
        lo32 = w64.to(tl.uint64).to(tl.uint32)
        hi32 = (w64.to(tl.uint64) >> 32).to(tl.uint32)
        words = tl.interleave(
            lo32.to(tl.int32, bitcast=True),
            hi32.to(tl.int32, bitcast=True),
        )  # [BLOCK_K, BLOCK_N/8] — memory order preserved
        m = (
            ((words[:, :, None] >> shift[None, None, :]) & 0xF) | 0x6400
        ).reshape(BLOCK_K, BLOCK_N)
        q = m.to(tl.uint16).to(tl.float16, bitcast=True) - 1024.0
        x = tl.load(x_ptr + rk, mask=kmask, other=0.0)
        prod = (q * x[:, None]).to(tl.float32)
        pqx = tl.sum(prod, axis=0)
        xs = tl.sum(x.to(tl.float32), axis=0)

        g = k0 // GS
        rw32 = pid_n * (BLOCK_N // 8) + tl.arange(0, BLOCK_N // 8)
        zwords = tl.load(
            qz_ptr + g * s_qzk + rw32 * s_qzn,
            mask=rw32 < (N + 7) // 8,
            other=0,
        )
        zm = ((zwords[:, None] >> shift[None, :]) & 0xF) | 0x6400
        z = (
            zm.reshape(BLOCK_N).to(tl.uint16).to(tl.float16, bitcast=True)
            - 1024.0
        ).to(tl.float32)
        s = tl.load(
            sc_ptr + g * s_sck + rn * s_scn, mask=nmask, other=0.0
        ).to(tl.float32)
        acc += s * (pqx - z * xs)

    tl.store(part_ptr + pid_k * s_pk + rn * s_pn, acc, mask=nmask)
"#;

    let reduce = r#"

@triton.jit
def _reduce(part_ptr, out_ptr, N, SPLIT, s_pk, s_pn, BLOCK: tl.constexpr):
    """Sum the SPLIT partial rows into the fp16 output."""
    pid = tl.program_id(0)
    rn = pid * BLOCK + tl.arange(0, BLOCK)
    mask = rn < N
    acc = tl.zeros((BLOCK,), dtype=tl.float32)
    for j in range(SPLIT):
        acc += tl.load(
            part_ptr + j * s_pk + rn * s_pn, mask=mask, other=0.0
        )
    tl.store(out_ptr + rn, acc.to(tl.float16), mask=mask)
"#;

    let runner = r#"

def run(x, qw, qz, sc, n, k, bn=BLOCK_N_DEFAULT, bk=BLOCK_K_DEFAULT,
        warps=2, out=None):
    """Run the lowered kernel. The term, not the caller, fixes K/SPLIT."""
    if k != K:
        raise ValueError(f"lowered for K={K}, called with k={k}")
    if bk > GROUP:
        raise ValueError(
            f"hoisted dequant needs BLOCK_K <= GROUP ({GROUP}), got {bk}"
        )
    parts = torch.empty((SPLIT, n), device="cuda", dtype=torch.float32)
    if qw.shape[1] % 2 == 0 and qw.is_contiguous():
        qw64 = qw.view(torch.int64)
        _stage1_w64[(triton.cdiv(n, bn), SPLIT)](
            x,
            qw64,
            qz,
            sc,
            parts,
            n,
            k,
            GROUP,
            SPLIT,
            qw64.stride(0),
            qw64.stride(1),
            qz.stride(0),
            qz.stride(1),
            sc.stride(0),
            sc.stride(1),
            parts.stride(0),
            parts.stride(1),
            BLOCK_N=bn,
            BLOCK_K=bk,
            num_warps=warps,
            num_stages=PIPELINE_DEPTH,
        )
    else:
        _stage1[(triton.cdiv(n, bn), SPLIT)](
            x,
            qw,
            qz,
            sc,
            parts,
            n,
            k,
            GROUP,
            SPLIT,
            qw.stride(0),
            qw.stride(1),
            qz.stride(0),
            qz.stride(1),
            sc.stride(0),
            sc.stride(1),
            parts.stride(0),
            parts.stride(1),
            BLOCK_N=bn,
            BLOCK_K=bk,
            num_warps=warps,
            num_stages=PIPELINE_DEPTH,
        )
    if out is None:
        out = torch.empty((1, n), device="cuda", dtype=torch.float16)
    _reduce[(triton.cdiv(n, 128),)](
        parts,
        out,
        n,
        SPLIT,
        parts.stride(0),
        parts.stride(1),
        BLOCK=128,
    )
    return out
"#;

    format!("{header}{stage1}{reduce}{runner}")
}

// -- ADR-0171: elementwise/layout fragment ----------------------------------
//
// `store(body, out)` where `body` is a tree of the pointwise ops over leaf
// operands. One Triton kernel: a flat 1-D grid over the broadcast output,
// each element's flat index decomposed into <=4 coordinates (left-padded
// with size-1 dims), and every operand addressed by per-dimension
// effective strides — a broadcast or absent dim simply contributes 0.
// `transpose`/`permute` never reach the kernel: they are torch *views*
// (Cost() zero in the IR) applied host-side before launch, so the kernel
// sees only the permuted strides. Rank > 4 declines loudly in `run`.

/// Render one operand's view list as a Python literal.
fn views_py(views: &[View]) -> String {
    let parts: Vec<String> = views
        .iter()
        .map(|v| match v {
            View::Transpose(d0, d1) => format!("(\"transpose\", {d0}, {d1})"),
            View::Permute(dims) => {
                let ds: Vec<String> = dims.iter().map(|d| d.to_string()).collect();
                format!("(\"permute\", ({}))", ds.join(", "))
            }
        })
        .collect();
    if parts.is_empty() {
        "()".to_string()
    } else {
        format!("({},)", parts.join(", "))
    }
}

fn operand_py(o: &Operand) -> String {
    format!("({:?}, {})", o.name, views_py(&o.views))
}

/// Triton expression for one elementwise node. `p{i}`/`s{i}_{d}` are the
/// kernel's pointer and per-dim stride arguments for operand `i`.
fn gen_expr(e: &Expr) -> String {
    match e {
        Expr::Load(i) => format!(
            "tl.load(p{i} + c0*s{i}_0 + c1*s{i}_1 + c2*s{i}_2 + c3*s{i}_3, \
             mask=mask, other=0)"
        ),
        Expr::Lit(Lit::Int(v)) => v.to_string(),
        Expr::Lit(Lit::Float(v)) => {
            if v.fract() == 0.0 {
                format!("{v:.1}")
            } else {
                format!("{v}")
            }
        }
        Expr::Unary(op, a) => {
            let ga = gen_expr(a);
            match *op {
                "neg" => format!("(-({ga}))"),
                "relu" => {
                    format!("tl.maximum({ga}, tl.zeros_like({ga}))")
                }
                "exp" => format!("tl.exp({ga})"),
                "sigmoid" => {
                    format!("(1.0 / (1.0 + tl.exp(-({ga}))))")
                }
                "tanh" => format!("libdevice.tanh({ga})"),
                "gelu" => format!(
                    "(0.5 * ({ga}) * (1.0 + tl.math.erf(({ga}) * \
                     0.7071067811865476)))"
                ),
                _ => format!("({ga}) * (1.0 / (1.0 + tl.exp(-({ga}))))"),
                // silu = x * sigmoid(x)
            }
        }
        Expr::Binary(op, a, b) => {
            let (ga, gb) = (gen_expr(a), gen_expr(b));
            match *op {
                "mul" => format!("({ga} * {gb})"),
                "sub" => format!("({ga} - {gb})"),
                _ => format!("({ga} + {gb})"), // bias
            }
        }
    }
}

/// Emit a Python module for an elementwise/layout term. `run` takes one
/// argument per bound leaf (read operands first, the store target last —
/// `None` allocates it) plus `block`/`warps`.
pub fn emit_elementwise(e: &Elementwise) -> String {
    let operands_lit = if e.operands.is_empty() {
        "()".to_string()
    } else {
        format!(
            "({},)",
            e.operands
                .iter()
                .map(operand_py)
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let env_lit = e
        .env
        .iter()
        .map(|(leaf, py)| format!("{leaf:?}: {py}"))
        .collect::<Vec<_>>()
        .join(", ");

    // run() signature: env order; the store target gets `=None` only when
    // it is not also a read leaf (out_nullable).
    let params: Vec<String> = e
        .env
        .iter()
        .map(|(_, py)| {
            if e.out_nullable && *py == e.out_var {
                format!("{py}=None")
            } else {
                py.clone()
            }
        })
        .collect();
    let sig = params.join(", ");

    // kernel params: pointers first, then shape, then strides — the same
    // order `run` passes them.
    let ptr_params: Vec<String> = (0..e.operands.len())
        .map(|i| format!("p{i}"))
        .chain(std::iter::once("out_p".to_string()))
        .collect();
    let stride_params: Vec<String> = (0..e.operands.len())
        .flat_map(|i| (0..4).map(move |d| format!("s{i}_{d}")))
        .chain((0..4).map(|d| format!("so_{d}")))
        .collect();

    let res = gen_expr(&e.expr);
    let store_val = match &e.expr {
        // a bare literal has no `.to`; materialise it as a block tensor
        Expr::Lit(_) => format!("tl.full((BLOCK,), {res}, tl.float32)"),
        _ => res,
    };

    let header = format!(
        r#""""Generated by compile-triton from a kernel IR term (ADR-0171).

Elementwise/layout fragment: `store(body, out)` lowered to one flat
Triton kernel over the broadcast output. `transpose`/`permute` are torch
views applied host-side (the IR prices them at zero); the kernel sees
only strides. Broadcast rank > 4 declines in `run`. Do not edit.
"""

import torch
import triton
import triton.language as tl
import triton.language.extra.libdevice as libdevice

# (leaf name, views) per read operand; views replay innermost-first.
_OPERANDS = {operands_lit}


def _es(t, cs):
    """Effective per-dim element strides of `t` against 4 padded canon dims."""
    r = t.dim()
    out = []
    for d in range(4):
        od = d - (4 - r)
        if od < 0 or t.shape[od] == 1:
            out.append(0)
        else:
            out.append(t.stride(od))
    return out


@triton.jit
def _elem_kernel(
    {ptr_params},
    NOUT,
    SH0,
    SH1,
    SH2,
    SH3,
    {stride_params},
    BLOCK: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < NOUT
    # decompose the flat row-major index into coords, SH3 fastest;
    # size-1 padding dims contribute coord 0 and stride 0
    c3 = offs % SH3
    r1 = offs // SH3
    c2 = r1 % SH2
    r2 = r1 // SH2
    c1 = r2 % SH1
    c0 = r2 // SH1
    res = {store_val}
    tl.store(
        out_p + c0*so_0 + c1*so_1 + c2*so_2 + c3*so_3,
        res.to(out_p.dtype.element_ty),
        mask=mask,
    )


def run({sig}, block=1024, warps=4):
    """Run the lowered elementwise kernel.

    Arguments bind the term's leaves in env order; the store target
    defaults to None (allocated with the broadcast shape and the promoted
    operand dtype). `transpose`/`permute` views are applied here as torch
    views — they move no bytes, matching the IR's zero cost.
    """
    env = {{{env_lit}}}
    tensors = []
    for name, vs in _OPERANDS:
        t = env[name]
        for v in vs:
            if v[0] == "transpose":
                t = t.transpose(v[1], v[2])
            else:
                t = t.permute(*v[1])
        tensors.append(t)
    out_t = {out_var}
    shapes = [tuple(t.shape) for t in tensors]
    if out_t is not None:
        shapes.append(tuple(out_t.shape))
    canon = torch.broadcast_shapes(*shapes) if shapes else ()
    if len(canon) > 4:
        raise ValueError(
            f"elementwise lowering supports broadcast rank <= 4, got {{canon}}"
        )
    cs = (1,) * (4 - len(canon)) + canon
    numel = 1
    for d in canon:
        numel *= d
    if numel == 0:
        if out_t is None:
            dt = tensors[0].dtype if tensors else torch.float32
            for t in tensors[1:]:
                dt = torch.promote_types(dt, t.dtype)
            device = tensors[0].device if tensors else "cpu"
            out_t = torch.empty(canon, dtype=dt, device=device)
        return out_t
    if out_t is None:
        dt = tensors[0].dtype if tensors else torch.float32
        for t in tensors[1:]:
            dt = torch.promote_types(dt, t.dtype)
        device = tensors[0].device if tensors else "cpu"
        out_t = torch.empty(canon, dtype=dt, device=device)
    _elem_kernel[(triton.cdiv(numel, block),)](
        *tensors,
        out_t,
        numel,
        cs[0],
        cs[1],
        cs[2],
        cs[3],
        *[s for t in tensors for s in _es(t, cs)],
        *_es(out_t, cs),
        BLOCK=block,
        num_warps=warps,
    )
    return out_t
"#,
        operands_lit = operands_lit,
        ptr_params = ptr_params.join(", "),
        stride_params = stride_params.join(", "),
        store_val = store_val,
        sig = sig,
        env_lit = env_lit,
        out_var = e.out_var,
    );

    header
}
